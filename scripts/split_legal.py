"""Split the master legal file into one clean file per document and
write the SQL that registers each document version with its SHA-256.

Run after any change to docs/legal/legal-texts-<lang>-v<version>.md:
    python3 scripts/split_legal.py
Changing a document's text means bumping its version, so old consent
records keep pointing at the exact text that was agreed to.
"""
import hashlib, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = {"en": ROOT / "docs/legal/legal-texts-en-v1.md"}
# (key, title line prefix, stop before next line starting with)
DOCS = [
    ("terms", "**Obsidian Cup Account Terms of Use"),
    ("privacy", "**Obsidian Cup Privacy Notice"),
    ("media", "**Obsidian Cup Media Consent"),
    ("participation", "**Obsidian Cup Event Participation Agreement"),
    ("payment", "**Obsidian Cup Payment, Refund and Event Change Policy"),
    ("guardian", "**Obsidian Cup Parent / Guardian Consent"),
    ("captain_code", "**Captain Code Terms"),
    ("captain_declaration", "**Captain Declaration"),
]
# Short declarations that are agreed to by a checkbox but have no long text
DECLARATIONS = {
    "dob_declaration": ("Date of birth declaration",
                        "I confirm that the date of birth I enter is my real date of birth."),
    "media_feature": ("Individual feature in promotional posts (optional)",
                      "I agree that Obsidian Cup may feature me individually in promotional posts, "
                      "such as player spotlights, highlight clips centred on me, and posters."),
}

def extract(lines, start_prefix):
    start = next(i for i, l in enumerate(lines) if l.startswith(start_prefix))
    end = len(lines)
    for j in range(start + 1, len(lines)):
        l = lines[j]
        if l.startswith("## ") or (l.startswith("**") and "— version" in l):
            end = j
            break
    body = "\n".join(lines[start:end]).strip() + "\n"
    title_line = lines[start].strip("* ")
    title, version = title_line.rsplit(" — version ", 1)
    return title.strip(), version.strip(), body

rows = []
for lang, src in SOURCES.items():
    lines = src.read_text(encoding="utf-8").splitlines()
    outdir = ROOT / "legal" / lang
    outdir.mkdir(parents=True, exist_ok=True)
    for key, prefix in DOCS:
        title, version, body = extract(lines, prefix)
        path = outdir / f"{key}-{version}.md"
        path.write_text(body, encoding="utf-8")
        sha = hashlib.sha256(body.encode("utf-8")).hexdigest()
        rows.append((key, version, lang, title, sha, f"/legal/{lang}/{key}-{version}.md"))
    for key, (title, text) in DECLARATIONS.items():
        sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
        rows.append((key, "1.0", lang, title, sha, None))

def q(v):
    return "null" if v is None else "'" + str(v).replace("'", "''") + "'"

sql = ["-- Generated by scripts/split_legal.py. Do not edit by hand.",
       "insert into public.legal_documents (key, version, lang, title, sha256, url) values"]
sql.append(",\n".join("  (" + ", ".join(q(v) for v in r) + ")" for r in rows))
sql[-1] += "\non conflict (key, version, lang) do update set title = excluded.title, sha256 = excluded.sha256, url = excluded.url;"
(ROOT / "supabase" / "seed").mkdir(parents=True, exist_ok=True)
(ROOT / "supabase/seed/legal_documents.sql").write_text("\n".join(sql) + "\n", encoding="utf-8")
for r in rows:
    print(r[0], r[1], r[2], r[4][:12], r[5])
