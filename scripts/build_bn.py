"""Build js/lang-site.js from the organiser's Bangla.

Inputs (both in docs/translation/):
  site-text.json    every piece of site text: id, section, English
  bn-received.json  the organiser's Bangla, by id

Run after adding new Bangla:  python3 scripts/build_bn.py
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
entries = json.loads((ROOT / "docs/translation/site-text.json").read_text(encoding="utf-8"))
bn = json.loads((ROOT / "docs/translation/bn-received.json").read_text(encoding="utf-8"))
norm = lambda s: re.sub(r"\s+", " ", s or "").strip()

by_text, by_id, acct = {}, {}, {}
for e in entries:
    t = bn.get(e["id"], "").strip()
    if not t:
        continue
    if e["id"].startswith("acct."):
        acct[e["id"][5:]] = t
    else:
        by_id[e["id"]] = t
        by_text[norm(e["en"])] = t

def js(obj):
    return json.dumps(obj, ensure_ascii=False, indent=1, sort_keys=True)

out = f"""// Generated by scripts/build_bn.py from docs/translation/. Do not edit by hand.
// The organiser's Bangla for the whole site.
// OC_BN_TEXT: matched by the English wording on the page.
const OC_BN_TEXT = {js(by_text)};
// Keyed text (data-key="<id>" on the page).
Object.assign(TRANSLATIONS.bn, {js(by_id)});
// Player account pages (merged into OC_TEXT.bn by js/oc-accounts.js).
const OC_SITE_BN_ACCT = {js(acct)};
"""
(ROOT / "js/lang-site.js").write_text(out, encoding="utf-8")
print(f"{len(by_text)} site lines, {len(acct)} account lines")
